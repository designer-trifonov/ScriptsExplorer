"use strict";
/**
 * Единственная формула масштаба содержимого песочницы в зависимости от
 * глубины вложенности. Корень — глубина 0, масштаб 1. Каждый следующий
 * уровень вложенности (песочница внутри песочницы) — масштаб родителя ×
 * SCALE_STEP. Всё, что рисует или раскладывает содержимое песочницы на
 * заданной глубине (размер слота скрипта, шаг сетки/margin, авторазмер
 * самой песочницы что в renderer, что в main через IPC) берёт готовый
 * scaleForDepth(depth) — никто не хардкодит "уменьшить на 20%" отдельно
 * у себя, и сама глубина ни в кого не "зашита": рекурсия buildBox просто
 * увеличивает depth на 1 на каждом вложении, а дальше всё считается этой
 * единственной формулой.
 */
const SCALE_STEP = 0.8;

function scaleForDepth(depth) {
  return SCALE_STEP ** depth;
}

export { SCALE_STEP, scaleForDepth };
