"use strict";
/**
 * Формула приоритета песочниц: в каком порядке они получают место при
 * упаковке (см. gridPack.js — она делает саму раскладку, для всех
 * элементов разом, включая скрипты). Сперва самая большая по площади
 * песочница, дальше по убыванию — так крупные элементы занимают место
 * первыми и не оставляют больших дыр, которые потом нечем заполнить.
 */

/** items — [{key, w, h}, ...]. Возвращает новый массив, отсортированный по убыванию площади. */
export function prioritizeSandboxes(items) {
  return [...items].sort((a, b) => (b.w * b.h) - (a.w * a.h));
}
