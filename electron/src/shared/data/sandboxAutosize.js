"use strict";
/**
 * Считает, каким должен стать размер песочницы, чтобы вместить её
 * содержимое — выровненным по сетке "слотов" (одна карточка скрипта +
 * её отступ), а не произвольным числом. Один ряд содержимого — высота
 * ровно один слот, два ряда — ровно два, и так далее (то же самое по
 * ширине/колонкам). Порт data/sandbox_autosize.py, переработан под явное
 * требование "высота/ширина песочницы кратна высоте/ширине слота".
 *
 * Ничего не знает о конкретных пикселях карточки/отступа и о вложенности
 * песочниц — slotW/slotH/margin передаёт вызывающая сторона (renderer,
 * единственный владелец константы SANDBOX_MARGIN/CELL_W/CELL_H и формулы
 * масштаба по глубине — см. sandboxScale.js). Так эти числа не дублируются
 * по разные стороны main/renderer, а расчёт сетки остаётся одной и той же
 * функцией на любой глубине вложенности — просто с другими slotW/slotH.
 */
const { getLogger } = require("../../main/logger");

const logger = getLogger("sandboxAutosize");

/**
 * itemPositions — [[x, y, w, h], ...] уже размещённых элементов (координаты
 * внутри содержимого песочницы). slotW/slotH — размер одной ЯЧЕЙКИ сетки на
 * этой глубине вложенности (сами элементы сетки идут впритык друг к другу,
 * без зазора — см. gridPack). margin — единственный отступ от края
 * содержимого до сетки, одинаковый со всех четырёх сторон. Возвращает
 * [width, height] — минимум один слот + отступы по краям, даже для пустой
 * песочницы.
 */
function requiredSize(itemPositions, slotW, slotH, margin) {
  if (itemPositions.length === 0) {
    logger.info(`Пустая песочница — минимум один слот ${[slotW, slotH]}`);
    return [slotW, slotH];
  }

  const maxX = Math.max(...itemPositions.map(([x, , w]) => x + w));
  const maxY = Math.max(...itemPositions.map(([, y, , h]) => y + h));

  const cols = Math.max(1, Math.ceil((maxX - margin) / slotW));
  const rows = Math.max(1, Math.ceil((maxY - margin) / slotH));
  // Отступ — не опциональная косметика, а часть требуемого места: он уже
  // заложен слева/сверху (элементы стоят с координаты margin), здесь
  // добавляем точно такой же отступ справа/снизу. Если из-за этого
  // содержимое не влезает в текущий (уже round-up'нутый до целого числа
  // РОДИТЕЛЬСКИХ слотов, см. sandboxController.js) размер — вызывающая
  // сторона обязана вырастить песочницу ещё на слот по нужной оси, а не
  // тут ужать отступ, чтобы "впихнуть" контент.
  const size = [cols * slotW + margin * 2, rows * slotH + margin * 2];

  logger.info(`Требуемый размер песочницы под ${itemPositions.length} элементов: ${size} (${cols}x${rows} слотов)`);
  return size;
}

module.exports = { requiredSize };
